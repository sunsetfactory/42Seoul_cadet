int	atoi(const char *str)
{
	int	res;
	int	i;
	int	c;

	res = 0;
	i = 0;
	c = 1;
	while ((9 <= str[i] && str[i] <= 13) || str[i] == 32)
		i++;
	if (str[i] == '+' || str[i] == '-')
	{
		if (str[i] == '-')
			c = -c;
		i++;
	}
	while (('0' <= str[i] && str[i] <= '9'))
	{
		res = res * 10 + (str[i] - '0');
		i++;
	}
	return (c * res);
}
